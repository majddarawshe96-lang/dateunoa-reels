"""Render one day's 9 quote reels with mood-matched music.

Usage: python3 tools/render_day.py <content_file> <YYYY-MM-DD> [--only 2,3,...] [--copy]
  content_file: content/days/<date>.py (or content/week1.py) defining DAYS.
  Mood per quote: the post's 4th item if present ("tender", "melancholy", "playful", "confident",
  "hopeful"), else content/moods.json, else a guess from the pillar and the words.
  Music comes from tools/music/<mood>/<mood>_NN.m4a (original, generated by tools/make_mood_music.py);
  the variation rotates by day so the same quote type doesn't always get the same track.
  Writes out/<date>/reel_N.mp4; with --copy also copies them to reels/<date>/dq_0N.mp4.
"""
import importlib.util
import json
import re
import shutil
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MOODS = ["tender", "melancholy", "playful", "confident", "hopeful"]
PILLAR_DEFAULT = {"T": "playful", "HE": "playful", "SHE": "tender", "M": "tender", "S": "confident", "W": "confident", "B": "hopeful"}
SAD = r"\b(left|leave|leaving|ghost\w*|gone|miss|alone|hurt|cry|seen|read|nothing|waiting|silence|vanish\w*|pattern|slow interest)\b"
STRONG = r"\b(standard\w*|allowed|deserve|worth|peace|clarity|certainty|real interest|nothing can stop|men:)\b"


def guess(pillar, quote):
    q = quote.lower()
    if re.search(SAD, q):
        return "melancholy"
    if re.search(STRONG, q):
        return "confident"
    return PILLAR_DEFAULT.get(pillar, "tender")


def main():
    a = sys.argv[1:]
    content, day = Path(a[0]), a[1]
    only = None
    if "--only" in a:
        only = {int(x) for x in a[a.index("--only") + 1].split(",")}
    spec = importlib.util.spec_from_file_location("content", content)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    posts = m.DAYS[day]["posts"]
    table = json.load(open(ROOT / "content" / "moods.json")).get(day, [])
    doy = date.fromisoformat(day).timetuple().tm_yday
    quotes, tracks, moods = [], [], []
    for i, p in enumerate(posts):
        mood = p[3] if len(p) > 3 else (table[i] if i < len(table) else guess(p[0], p[1]))
        assert mood in MOODS, f"unknown mood {mood}"
        files = sorted((ROOT / "tools" / "music" / mood).glob(f"{mood}_*.m4a"))
        tracks.append(str(files[(doy + i) % len(files)]))
        quotes.append(p[1])
        moods.append(mood)
    out = ROOT / "out" / day
    subprocess.run([sys.executable, str(ROOT / "tools" / "make_post.py"), "--tracks", ",".join(tracks),
                    str(ROOT / "tools" / "avatar.jpg"), str(out), "dateunoa", *quotes], check=True)
    for i, (mood, t) in enumerate(zip(moods, tracks), 1):
        print(f"{day} dq_{i:02d}: {mood} ({Path(t).name})")
    if "--copy" in a:
        dst = ROOT / "reels" / day
        dst.mkdir(parents=True, exist_ok=True)
        for i in range(1, len(quotes) + 1):
            if only and i not in only:
                continue
            shutil.copy(out / f"reel_{i}.mp4", dst / f"dq_{i:02d}.mp4")
        print("copied to", dst)


if __name__ == "__main__":
    main()
